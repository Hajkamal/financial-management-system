import {build} from 'esbuild';import {writeFile} from 'node:fs/promises';
// Bundle first-party modules so Vercel's native ESM loader never sees extensionless local imports.
// External packages and runtime environment variables remain external; no credentials are embedded.
const result=await build({stdin:{contents:"import {app} from './serverApp'; export default app;",resolveDir:process.cwd(),sourcefile:'vercel-entry.ts',loader:'ts'},bundle:true,platform:'node',target:'node22',format:'esm',packages:'external',write:false,sourcemap:false});
const entry='// @ts-nocheck\n// Generated by scripts/build-vercel-entry.mjs. Do not edit directly.\n'+result.outputFiles[0].text+'\nexport const maxDuration = 60;\n';
await writeFile('api/[...path].ts',entry);
await writeFile('api/index.ts',entry);
